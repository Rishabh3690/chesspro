export type PuzzleSkillTier = 'Beginner' | 'Intermediate' | 'Expert';

export interface PuzzleSkillBadgeInfo {
  tier: PuzzleSkillTier;
  label: PuzzleSkillTier;
  shortLabel: string;
  rangeLabel: string;
  badgeClass: string;
  activeBadgeClass: string;
  dotClass: string;
}

/**
 * Categorizes a Lichess tactical puzzle rating into a visual skill level tier:
 * - Beginner: < 1650
 * - Intermediate: 1650 - 1999
 * - Expert: 2000+ (Very Hard Grandmaster Mate-in-2 sacrifices & deflections)
 */
export function getPuzzleSkillTier(rating: number): PuzzleSkillBadgeInfo {
  if (rating < 1650) {
    return {
      tier: 'Beginner',
      label: 'Beginner',
      shortLabel: 'BEG',
      rangeLabel: '<1650',
      badgeClass: 'bg-sky-500/15 text-sky-200 border border-sky-400/30',
      activeBadgeClass: 'bg-sky-950/70 text-sky-100 border border-sky-300/50',
      dotClass: 'bg-sky-300',
    };
  }
  if (rating < 2000) {
    return {
      tier: 'Intermediate',
      label: 'Intermediate',
      shortLabel: 'INT',
      rangeLabel: '1650–1999',
      badgeClass: 'bg-indigo-500/15 text-indigo-200 border border-indigo-400/30',
      activeBadgeClass:
        'bg-indigo-950/70 text-indigo-100 border border-indigo-300/50',
      dotClass: 'bg-indigo-300',
    };
  }
  return {
    tier: 'Expert',
    label: 'Expert',
    shortLabel: 'EXP',
    rangeLabel: '2000+',
    badgeClass: 'bg-slate-200/15 text-white border border-slate-200/40',
    activeBadgeClass: 'bg-slate-800/80 text-white border border-white/60',
    dotClass: 'bg-white',
  };
}

